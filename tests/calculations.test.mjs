import assert from 'node:assert/strict';
import {addDays,daysBetween,numberDE,estimateReadingFromOCR,calculate,validState} from '../calculations.mjs';
const base=()=>({schemaVersion:1,settings:{baselineKwh:10396,periodStart:'2026-05-19',periodEnd:'2027-05-19',invoiceDate:'2027-06-18'},tariffs:[{id:'old',from:'2026-05-20',priceCt:30.3569,baseYear:180}],readings:[],payments:Array.from({length:11},(_,i)=>({id:`a${i}`,date:`2026-08-01`,amount:94,paid:false}))});
assert.equal(daysBetween('2026-05-19','2027-05-19'),365,'Ein Jahreszeitraum hat 365 Tage');
assert.equal(daysBetween('2024-02-28','2024-03-01'),2,'Schaltjahr');
assert.equal(addDays('2026-12-31',1),'2027-01-01');
assert.equal(numberDE('10.396'),10396);
assert.equal(numberDE('10.396,50'),10396.5);
assert.equal(numberDE('30,3569'),30.3569);
assert.equal(estimateReadingFromOCR('Zähler 11750',10396),11750);
assert.equal(estimateReadingFromOCR('kein Ergebnis',10396),null);
let s=base();validState(s);let empty=calculate(s,'2026-11-09');
assert.equal(empty.measuredKwh,0);assert.equal(empty.forecastCost,null);
s.readings=[{id:'x',date:'2026-06-19',kwh:10696}];let actual=calculate(s,'2026-11-09');
assert.equal(actual.elapsed,31);assert.equal(actual.measuredKwh,300);
assert.ok(Math.abs(actual.measuredEnergyCost-(300*.303569))<.001);
assert.ok(Math.abs(actual.measuredBaseCost-(31*180/365))<.001);
assert.ok(Math.abs(actual.forecastKwh-(300*365/31))<.001);
assert.equal(actual.forecastPayments,1034);
assert.ok(Math.abs(actual.forecastCost-((300*365/31)*.303569+180))<.001);
assert.ok(Math.abs(actual.forecastBalance-(1034-actual.forecastCost))<.001);
let t=base();t.readings=[{id:'a',date:'2026-06-18',kwh:10696}];
t.tariffs.push({id:'new',from:'2026-06-04',priceCt:40,baseYear:365});
let changed=calculate(t,'2026-06-18');
// 15 days at old price, 15 days at new price, with evenly distributed 10 kWh per day.
assert.ok(Math.abs(changed.measuredEnergyCost-(150*.303569+150*.4))<.001);
assert.ok(Math.abs(changed.measuredBaseCost-(15*180/365+15*365/365))<.001);
const back=base();back.readings=[{id:'a',date:'2026-06-01',kwh:10500},{id:'b',date:'2026-06-08',kwh:10490}];
assert.throws(()=>validState(back),/rückwärts/);
const badDate=base();badDate.readings=[{id:'a',date:'2026-02-30',kwh:11000}];assert.throws(()=>validState(badDate),/Ungültiges Datum/);
console.log('Berechnungen: 16 Prüfungen bestanden.');
